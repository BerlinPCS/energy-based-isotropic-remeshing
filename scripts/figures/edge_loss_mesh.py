"""Generate the mesh versions of the edge-loss figures of Chapter 3 (DRAFT).

edge-loss-mesh.tikz (Figure fig:edge-loss, Section sec:energy), target length L = 1:
(a) A flat patch cut from a jittered equilateral lattice with edge length L. One vertex is removed, leaving an edge
    of length exactly 2L, and one edge is split at its midpoint, leaving two edges of exactly L/2. Edge colour and
    width show the loss lambda = log2(l/L)^2, so the long edge and the two short edges look the same (lambda = 1).
    The sum, the edge count and the average of the patch are printed below it.
(b) The squared property: two triangles sharing an edge of length 4L, whose opposite vertices lie L from its
    midpoint. Splitting it replaces the loss 4 of the edge by 1 + 1 for the halves and 0 for the two new edges.
    Without the square, |log2| would rate the halves 1 + 1 = 2, the same as the original edge.

split-objectives.tikz (Figure fig:split-objectives, Section sec:queue):
(a, b) One split of an edge of length 1.445 L whose opposite vertices lie L from its midpoint, in an idealized patch
    (the two triangles of the edge and their neighbours) whose boundary edges continue as faded stubs into the rest
    of the mesh. The before set (orange) and after set (teal) of Table tab:operations carry their losses; the mesh
    is only symbolic, with energy E and |E| edges before and E + 0.16, |E| + 3 after. The length is chosen so that every
    printed number follows from the printed losses 0.28 and 0.22 (with 1.45 L the sum after would print as 0.43).
(c) The four objectives: the sum rejects the split, the local average and the maximum accept it. The global average
    is shown for two average losses of the mesh: the split raises the energy by 0.16, so by the text's rule
    g_sum + d_o * avg(B) > 0 it is rejected at avg = 0.03 and accepted at avg = 0.10 (threshold 0.053), while the
    local average allows 3 * lambda(e) = 0.85. Objective gains and verdicts are green if positive, red if negative.

All numbers in the figures are computed here and asserted.
"""

import math
import random

from common.style import define_color

L = 1.0
S3 = math.sqrt(3) / 2

COLORS = [
    define_color("opInk") + "%",
    define_color("opNeutral") + "%",
    define_color("opBefore") + "%",
    define_color("opAfter") + "%",
]

# Loss ramp: one hue, light to dark, with lambda = 1 at the thesis orange. Colour and width follow t = |log2(l/L)|/2,
# that is sqrt(lambda)/2, clipped to [0, 1]; the key prints the corresponding lambda values.
RAMP = [(0.0, "C9C3BD"), (0.5, "D77D43"), (1.0, "6E2A0D")]


def loss(length):
    return math.log2(length / L) ** 2


def hex_to_rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def ramp(t):
    t = min(max(t, 0.0), 1.0)
    for (t0, c0), (t1, c1) in zip(RAMP, RAMP[1:]):
        if t <= t1:
            a, b, s = hex_to_rgb(c0), hex_to_rgb(c1), (t - t0) / (t1 - t0)
            return tuple(round(x + (y - x) * s) for x, y in zip(a, b))
    return hex_to_rgb(RAMP[-1][1])


def loss_t(length):
    return abs(math.log2(length / L)) / 2


def loss_style(length):
    r, g, b = ramp(loss_t(length))
    width = 0.45 + 1.5 * min(loss_t(length), 1.0)
    return f"draw={{rgb,255:red,{r};green,{g};blue,{b}}},line width={width:.2f}pt,line cap=round"


def edges(faces):
    return sorted({tuple(sorted(e)) for f in faces for e in ((f[0], f[1]), (f[1], f[2]), (f[2], f[0]))})


def signed_area(pos, f):
    (ax, ay), (bx, by), (cx, cy) = (pos[x] for x in f)
    return 0.5 * ((bx - ax) * (cy - ay) - (cx - ax) * (by - ay))


def ccw(pos, f):
    return f if signed_area(pos, f) > 0 else (f[0], f[2], f[1])


def length(pos, e):
    return math.dist(pos[e[0]], pos[e[1]])


def pt(pos, v, dx=0.0, dy=0.0):
    return f"({pos[v][0] + dx:.4f},{pos[v][1] + dy:.4f})"


def draw_mesh(pos, faces, edge_style, shift=(0.0, 0.0), skip=()):
    dx, dy = shift
    s = []
    for f in faces:
        s.append("\\fill[opNeutral] " + " -- ".join(pt(pos, v, dx, dy) for v in f) + " -- cycle;%")
    for e in edges(faces):
        if e not in skip:
            s.append(f"\\draw[{edge_style(e)}] {pt(pos, e[0], dx, dy)} -- {pt(pos, e[1], dx, dy)};%")
    return s


def draw_vertices(pos, faces, shift=(0.0, 0.0), fill=None):
    dx, dy = shift
    fill = fill or {}
    return [f"\\draw[em vertex,fill={fill.get(v, 'white')}] {pt(pos, v, dx, dy)} circle[radius=1.3pt];%"
            for v in sorted({v for f in faces for v in f})]


def header(source):
    return [f"% Generated by scripts/figures/{source} (DRAFT); edit the generator, not this file.%", "\\begingroup%",
            *COLORS,
            "\\begin{tikzpicture}[%",
            "  em vertex/.style={draw=opInk,line width=.4pt},%",
            "  em edge/.style={draw=opInk!45,line width=.45pt,line cap=round},%",
            "  em before/.style={draw=opBefore,line width=1.6pt,line cap=round},%",
            "  em after/.style={draw=opAfter,line width=1.6pt,line cap=round},%",
            "  em label/.style={font=\\scriptsize,text=opInk,inner sep=1pt},%",
            "  em title/.style={font=\\footnotesize\\bfseries,text=opInk,anchor=west}]%"]


FOOTER = ["\\end{tikzpicture}%", "\\endgroup%"]


