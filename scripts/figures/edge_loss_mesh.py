RATIO = 1.445  # not 1.45: the printed sum after the split must equal the sum of the printed losses
STUB = 0.42  # drawn fraction of an edge that leaves the patch
GLOBAL_AVGS = (0.03, 0.10)  # average losses of the mesh before the split, for the two global-average rows


def split_patch():
    """An idealized patch around a split edge of length RATIO*L whose opposite vertices lie L from its midpoint: the
    two triangles of the edge and their neighbours, in rows of height L. The edges that connect the patch to the next
    ring of the mesh are returned as stubs (inner vertex first), so the figure can draw them cut off."""
    h = RATIO / 2
    rows = {0: [-2 - h, -1 - h, -h, h, 1 + h, 2 + h], 1: [-2, -1, 0, 1, 2], -1: [-2, -1, 0, 1, 2],
            2: [-1.5, -0.5, 0.5, 1.5], -2: [-1.5, -0.5, 0.5, 1.5]}
    inner = {f"0:{i}" for i in range(1, 5)} | {f"{r}:{i}" for r in (1, -1) for i in range(1, 4)}
    pos = {f"{r}:{i}": (x * L, r * L) for r, xs in rows.items() for i, x in enumerate(xs)}
    ring = []
    for r0, r1 in ((0, 1), (0, -1), (1, 2), (-1, -2)):  # zip two neighbouring rows into a strip of triangles
        A = [f"{r0}:{i}" for i in range(len(rows[r0]))]
        B = [f"{r1}:{i}" for i in range(len(rows[r1]))]
        i = j = 0
        while i < len(A) - 1 or j < len(B) - 1:
            if j == len(B) - 1 or (i < len(A) - 1 and pos[A[i + 1]][0] <= pos[B[j + 1]][0]):
                ring.append(ccw(pos, (A[i], A[i + 1], B[j])))
                i += 1
            else:
                ring.append(ccw(pos, (A[i], B[j + 1], B[j])))
                j += 1
    faces = [f for f in ring if set(f) <= inner]
    stubs = [(u, v) if u in inner else (v, u) for u, v in edges(ring) if (u in inner) != (v in inner)]
    assert len(faces) == 10 and {e for e in edges(ring) if set(e) <= inner} == set(edges(faces))
    a, b, w, x = "0:2", "0:3", "1:2", "-1:2"
    assert abs(length(pos, (a, b)) - RATIO * L) < 1e-12
    assert abs(math.dist(pos[w], (0, 0)) - L) < 1e-12 and abs(math.dist(pos[x], (0, 0)) - L) < 1e-12
    after = dict(pos, m=(0.0, 0.0))
    after_faces = []
    for f in faces:
        if a in f and b in f:
            (o,) = set(f) - {a, b}
            after_faces += [ccw(after, (a, "m", o)), ccw(after, ("m", b, o))]
        else:
            after_faces.append(f)
    assert all(signed_area(pos, f) > 0 for f in faces) and all(signed_area(after, f) > 0 for f in after_faces)
    return pos, faces, after, after_faces, stubs, (a, b), [(a, "m"), (b, "m"), ("m", w), ("m", x)]


def draw_stubs(pos, stubs, shift):
    """Edges into the rest of the mesh, cut off at STUB of their length and faded to the page colour."""
    dx, dy = shift
    s = []
    for u, v in stubs:
        (x0, y0), (x1, y1) = pos[u], pos[v]
        ang = math.degrees(math.atan2(y1 - y0, x1 - x0))
        s.append(f"\\begin{{scope}}[shift={{({x0 + dx:.4f},{y0 + dy:.4f})}},rotate={ang:.2f}]"
                 f"\\shade[left color=opInk!45,right color=white] (0,-.225pt) rectangle "
                 f"({STUB * math.dist(pos[u], pos[v]):.4f},.225pt);\\end{{scope}}%")
    return s


def split_objectives_figure(out):
    pos, faces, apos, afaces, stubs, split_edge, e_plus = split_patch()
    e_minus = [tuple(sorted(split_edge))]
    e_plus = [tuple(sorted(e)) for e in e_plus]
    lb = [loss(length(pos, e)) for e in e_minus]
    la = [loss(length(apos, e)) for e in e_plus]
    g_sum = sum(lb) - sum(la)
    agg = {
        "sum": (sum(lb), sum(la)),
        "local average": (sum(lb) / len(lb), sum(la) / len(la)),
        "maximum": (max(lb), max(la)),
    }
    gains = {k: b - a for k, (b, a) in agg.items()}
    # The sum rejects, the local average and the maximum accept. The global average of a mesh with |E| edges and
    # average loss avg changes by (g_sum + 3 avg) / (|E| + 3): it rejects the split below avg = -g_sum / 3 = 0.053
    # and accepts it above, while the local average allows 3 * lambda(e).
    assert gains["sum"] < 0 < gains["maximum"] < gains["local average"]
    lo, hi = GLOBAL_AVGS
    assert g_sum + 3 * lo < 0 < g_sum + 3 * hi
    # Every printed number must follow from the printed losses, so that a reader can redo the table by hand.
    le, lh = round(lb[0], 2), round(la[0], 2)
    assert all(abs(v) < 1e-12 for v in la[2:])
    checks = [(sum(la), 2 * lh), (gains["sum"], le - 2 * lh), (agg["local average"][1], lh / 2),
              (gains["local average"], le - lh / 2), (gains["maximum"], le - lh)]
    checks += [(g_sum + 3 * avg, le - 2 * lh + 3 * avg) for avg in GLOBAL_AVGS]
    for exact, shown in checks:
        assert math.isclose(shown, round(shown, 2)) and math.isclose(round(exact, 2), round(shown, 2)), (exact, shown)

    sc = 1.15
    P = {k: (x * sc, y * sc) for k, (x, y) in pos.items()}
    A = {k: (x * sc, y * sc) for k, (x, y) in apos.items()}
    stub_end = [(P[u][0] + STUB * (P[v][0] - P[u][0]), P[u][1] + STUB * (P[v][1] - P[u][1])) for u, v in stubs]
    half_w = max(abs(x) for x, _ in stub_end)
    half_h = max(abs(y) for _, y in stub_end)
    ox_b, ox_a, oy = half_w, 3 * half_w + 0.5, 0.0
    s = header("edge_loss_mesh.py")
    s += [define_color("opFail") + "%", define_color("opPass") + "%"]  # red as in Fig. 3.2
    s.append(f"% Split of an edge of length {RATIO} L, opposite vertices L from its midpoint, in an idealized patch.%")
    s.append("% " + ", ".join(f"{k}: {b:.4f} -> {a:.4f} (gain {gains[k]:+.5f})" for k, (b, a) in agg.items())
             + f"; global average: accepts iff avg > {-g_sum / 3:.4f}%")
    s.append(f"\\node[em title] at (0,{half_h + 0.25:.4f}) {{(a) before}};%")
    s.append(f"\\node[em title] at ({ox_a - half_w:.4f},{half_h + 0.25:.4f}) {{(b) after}};%")
    s += draw_stubs(P, stubs, (ox_b, oy))
    s += draw_mesh(P, faces, lambda e: "em edge", (ox_b, oy), skip=set(e_minus))
    for e in e_minus:
        s.append(f"\\draw[em before] {pt(P, e[0], ox_b, oy)} -- {pt(P, e[1], ox_b, oy)};%")
    s += draw_vertices(P, faces, (ox_b, oy))
    s.append(f"\\node[em label,fill=opNeutral,anchor=south] at ({ox_b:.4f},{oy + 0.06:.4f}) {{${lb[0]:.2f}$}};%")
    s += draw_stubs(A, stubs, (ox_a, oy))
    s += draw_mesh(A, afaces, lambda e: "em edge", (ox_a, oy), skip=set(e_plus))
    for e in e_plus:
        s.append(f"\\draw[em after] {pt(A, e[0], ox_a, oy)} -- {pt(A, e[1], ox_a, oy)};%")
    s += draw_vertices(A, afaces, (ox_a, oy), fill={"m": "opAfter"})
    hx = RATIO / 2 * sc * 0.4
    for xh in (-hx, hx):
        s.append(f"\\node[em label,fill=opNeutral,anchor=north] at ({ox_a + xh:.4f},{oy - 0.06:.4f}) "
                 f"{{${la[0]:.2f}$}};%")
    for yh in (0.5 * sc, -0.5 * sc):
        s.append(f"\\node[em label,fill=opNeutral,anchor=west] at ({ox_a + 0.05:.4f},{oy + yh:.4f}) {{$0$}};%")
    for ox, lab in ((ox_b, "$\\mathcal{E}$, \\ $|E|$, \\ $\\bar\\lambda=\\mathcal{E}/|E|$"),
                    (ox_a, f"$\\mathcal{{E}}+{-g_sum:.2f}$, \\ $|E|+3$")):
        s.append(f"\\node[em label,anchor=north] at ({ox:.4f},{oy - half_h - 0.12:.4f}) {{{lab}}};%")

    # (c) the four objectives. The global average is given for two average losses of the mesh. Its value after the
    # split is (E + 0.16) / (|E| + 3) with E = avg * |E|, as in the labels under (a) and (b); the gain, before minus
    # after, simplifies to (3 avg - 0.16) / (|E| + 3), whose sign does not depend on |E|.
    def colored(v, text):
        return f"\\textcolor{{{'opPass' if v > 0 else 'opFail'}}}{{{text}}}"

    def verdict(v):
        return colored(v, "yes" if v > 0 else "no")

    rows = [f"{k} & ${b:.2f}$ & ${a:.2f}$ & {colored(gains[k], f'${gains[k]:+.2f}$')} & {verdict(gains[k])}"
            for k, (b, a) in agg.items()]
    for avg in GLOBAL_AVGS:
        num = g_sum + 3 * avg
        after = f"({avg:.2f}|E|+{-g_sum:.2f})/(|E|+3)"
        rows.append(f"global average ($\\bar\\lambda={avg:.2f}$) & ${avg:.2f}$ & ${after}$ & "
                    f"{colored(num, f'${num:+.2f}/(|E|+3)$')} & {verdict(num)}")
    body = "\\\\".join(rows)
    # Below (a) and (b), centred between them.
    s.append(f"\\node[em label,anchor=north] (objectives) at ({(ox_b + ox_a) / 2:.4f},{oy - half_h - 1.15:.4f}) "
             f"{{\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}"
             f"& before & after & objective gain $g_{{\\bullet}}$ & accepted\\\\\\hline {body}\\end{{tabular}}}};%")
    s.append("\\node[em title,anchor=south west] at ([yshift=1pt]objectives.north west) {(c) objectives};%")
    s += FOOTER
    (out / "split-objectives.tikz").write_text("\n".join(s) + "\n")


