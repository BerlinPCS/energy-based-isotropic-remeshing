def lattice_patch():
    """Hexagonal patch of radius 2 of the equilateral lattice with edge length L, without its bottom row, with two
    local changes."""
    cells = [(q, r) for q in range(-2, 3) for r in range(-1, 3) if abs(q + r) <= 2]
    pos = {(q, r): (L * (q + r / 2), L * r * S3) for q, r in cells}
    faces = []
    for q, r in cells:
        for f in (((q, r), (q + 1, r), (q, r + 1)), ((q + 1, r), (q + 1, r + 1), (q, r + 1))):
            if all(v in pos for v in f):
                faces.append(f)

    # Remove the vertex (1, 0) and fill its hexagon with the diagonal (0,0)-(2,0) of length exactly 2L.
    removed = (1, 0)
    faces = [f for f in faces if removed not in f]
    del pos[removed]
    c, p, q_, r_, s, t = (0, 0), (0, 1), (1, 1), (2, 0), (2, -1), (1, -1)
    faces += [(c, r_, q_), (c, q_, p), (c, s, r_), (c, t, s)]

    # Split the edge (-1,0)-(-1,1) at its midpoint: two edges of exactly L/2.
    a, b, m = (-1, 0), (-1, 1), "m"
    pos[m] = tuple((x + y) / 2 for x, y in zip(pos[a], pos[b]))
    out = []
    for f in faces:
        if a in f and b in f:
            (w,) = set(f) - {a, b}
            out += [(a, m, w), (m, b, w)]
        else:
            out.append(f)
    faces = out

    # Jitter every vertex except those that fix the special lengths, so the patch looks like a real mesh.
    fixed = {c, r_, a, b, m}
    rng = random.Random(7)
    for v in sorted(pos, key=str):
        if v not in fixed:
            ang, rad = rng.uniform(0, 2 * math.pi), 0.11 * L * math.sqrt(rng.random())
            pos[v] = (pos[v][0] + rad * math.cos(ang), pos[v][1] + rad * math.sin(ang))
    name = lambda v: v if isinstance(v, str) else f"{v[0]},{v[1]}"
    pos = {name(v): xy for v, xy in pos.items()}
    faces = [ccw(pos, tuple(name(v) for v in f)) for f in faces]
    assert all(signed_area(pos, f) > 0.05 for f in faces)
    return pos, faces, tuple(sorted((name(c), name(r_)))), tuple(sorted((name(a), m))), tuple(sorted((m, name(b))))


def color_key(s, xc, ky, width=4.0, kh=0.16):
    """Colour key over the length ratio on a log axis, centred at xc, with the loss of the tick ratios above it.

    A smooth PGF shading: the ramp is linear in t = |log2(l/L)|/2 between its stops, so five stops at
    l/L = 1/4, 1/2, 1, 2, 4 reproduce it exactly."""
    stops = [ramp(abs(u) / 2) for u in (-2, -1, 0, 1, 2)]
    for i, (r, g, b) in enumerate(stops):
        s.append(f"\\definecolor{{lossKey{i}}}{{RGB}}{{{r},{g},{b}}}%")
    # TikZ maps the middle half (25bp to 75bp) of a 100bp shading onto the shaded path.
    s.append("\\pgfdeclarehorizontalshading{lossKey}{100bp}{color(0bp)=(lossKey0); " + "; ".join(
        f"color({25 + 12.5 * i}bp)=(lossKey{i})" for i in range(5)) + "; color(100bp)=(lossKey4)}%")
    kx0, kx1 = xc - width / 2, xc + width / 2
    s.append(f"\\shade[shading=lossKey] ({kx0:.4f},{ky:.4f}) rectangle ({kx1:.4f},{ky + kh:.4f});%")
    s.append(f"\\draw[opInk,line width=.3pt] ({kx0:.4f},{ky:.4f}) rectangle ({kx1:.4f},{ky + kh:.4f});%")
    for u, ratio in zip((-2, -1, 0, 1, 2), ("\\tfrac14", "\\tfrac12", "1", "2", "4")):
        x = kx0 + (kx1 - kx0) * (u + 2) / 4
        s.append(f"\\draw[opInk,line width=.3pt] ({x:.4f},{ky:.4f}) -- ({x:.4f},{ky - 0.06:.4f}) "
                 f"node[em label,anchor=north] {{${ratio}$}};%")
        s.append(f"\\node[em label,anchor=south] at ({x:.4f},{ky + kh:.4f}) {{${u * u}$}};%")
    s.append(f"\\node[em label,anchor=east] at ({kx0 - 0.1:.4f},{ky + kh + 0.12:.4f}) {{$\\lambda$}};%")
    s.append(f"\\node[em label,anchor=east] at ({kx0 - 0.1:.4f},{ky - 0.2:.4f}) {{$\\ell/\\ell_*$}};%")


def aligned(*rows):
    """Two-line label aligned at the equals signs."""
    return ("\\renewcommand{\\arraystretch}{.95}\\begin{tabular}{@{}r@{${}={}$}l@{}}"
            + "\\\\".join(f"${a}$&${b}$" for a, b in rows) + "\\end{tabular}")


def edge_loss_figure(out):
    pos, faces, long_edge, short1, short2 = lattice_patch()
    all_edges = edges(faces)
    lam = {e: loss(length(pos, e)) for e in all_edges}
    assert abs(length(pos, long_edge) - 2 * L) < 1e-12 and abs(loss(2 * L) - 1) < 1e-12
    assert abs(length(pos, short1) - L / 2) < 1e-12 and abs(length(pos, short2) - L / 2) < 1e-12
    total, count = sum(lam.values()), len(lam)
    avg = total / count

    s = header("edge_loss_mesh.py")
    s.append(f"% (a) {count} edges, E = {total:.4f}, average {avg:.4f}; long edge 2L and short edges L/2: lambda = 1.%")
    dx, dy = 3.25, 0.0
    top = max(y for _, y in pos.values()) + dy
    s.append(f"\\node[em title] at (0,{top + 0.45:.4f}) {{(a) edge loss}};%")
    for f in faces:
        s.append("\\fill[opNeutral] " + " -- ".join(pt(pos, v, dx, dy) for v in f) + " -- cycle;%")
    for e in sorted(all_edges, key=lambda e: lam[e]):  # dark edges on top
        s.append(f"\\draw[{loss_style(length(pos, e))}] {pt(pos, e[0], dx, dy)} -- {pt(pos, e[1], dx, dy)};%")
    s += draw_vertices(pos, faces, (dx, dy))

    # The short pair: one label with a leader line to the middle of each half.
    lab_x, lab_y = -1.45 + dx, 1.5 + dy  # leaders keep > 0.2 from every vertex
    short_lab = aligned(("\\ell", "\\tfrac12\\ell_*"), ("\\lambda", "1"))
    long_lab = aligned(("\\ell", "2\\ell_*"), ("\\lambda", "1"))
    s.append(f"\\node[em label,anchor=east] (shortlab) at ({lab_x:.4f},{lab_y:.4f}) {{{short_lab}}};%")
    for a, b in (short1, short2):
        mx, my = ((pos[a][0] + pos[b][0]) / 2 + dx, (pos[a][1] + pos[b][1]) / 2 + dy)
        s.append(f"\\draw[opInk,line width=.35pt] (shortlab.east) -- ({mx:.4f},{my:.4f});%")
    # The long edge.
    (lx0, ly0), (lx1, ly1) = pos[long_edge[0]], pos[long_edge[1]]
    ex, ey = lx0 + 0.72 * (lx1 - lx0) + dx, ly0 + 0.72 * (ly1 - ly0) + dy
    s.append(f"\\draw[opInk,line width=.35pt] ({ex:.4f},{ey - 0.03:.4f}) -- ({ex + 0.85:.4f},{ey - 0.5:.4f}) "
             f"node[em label,anchor=west] {{{long_lab}}};%")
    # Totals in the empty top-right corner of the patch, as in (b).
    s.append(f"\\node[em label,anchor=north west,align=left] at ({1.55 + dx:.4f},{top + 0.05:.4f}) "
             f"{{$\\mathcal{{E}}={total:.2f}$\\\\$|E|={count}$\\\\$\\bar\\lambda={avg:.3f}$}};%")
    bottom = min(y for _, y in pos.values()) + dy

    # (b) the squared property: split of an edge of length 4L.
    dpos = {"a": (-2 * L, 0.0), "b": (2 * L, 0.0), "w": (0.0, L), "x": (0.0, -L)}
    dfaces = [ccw(dpos, f) for f in (("a", "b", "w"), ("b", "a", "x"))]
    apos = dict(dpos, m=(0.0, 0.0))
    afaces = [ccw(apos, f) for f in (("a", "m", "w"), ("m", "b", "w"), ("m", "a", "x"), ("b", "m", "x"))]
    lam_before = {e: loss(length(dpos, e)) for e in edges(dfaces)}
    lam_after = {e: loss(length(apos, e)) for e in edges(afaces)}
    eb, ea = sum(lam_before.values()), sum(lam_after.values())
    assert abs(lam_before[("a", "b")] - 4) < 1e-12
    assert abs(lam_after[("a", "m")] - 1) < 1e-12 and abs(lam_after[("b", "m")] - 1) < 1e-12
    assert abs(lam_after[("m", "w")]) < 1e-12 and abs(lam_after[("m", "x")]) < 1e-12
    assert abs((eb - ea) - 2) < 1e-12

    sc = 0.65
    spos = {k: (x * sc, y * sc) for k, (x, y) in dpos.items()}
    sapos = {k: (x * sc, y * sc) for k, (x, y) in apos.items()}
    bx = 8.45
    by_top = top - sc
    by_bot = by_top - 2 * sc - 0.5
    s.append(f"% (b) before: E = {eb:.4f}, |E| = 5, avg {eb / 5:.4f}; after: E = {ea:.4f}, |E| = 8, avg {ea / 8:.4f}.%")
    s.append(f"\\node[em title] at ({bx - 2 * sc - 0.15:.4f},{top + 0.45:.4f}) {{(b) split $s$ of a long edge}};%")
    for P, F, (ox, oy), lam_d in ((spos, dfaces, (bx, by_top), lam_before), (sapos, afaces, (bx, by_bot), lam_after)):
        for f in F:
            s.append("\\fill[opNeutral] " + " -- ".join(pt(P, v, ox, oy) for v in f) + " -- cycle;%")
        for e in sorted(edges(F), key=lambda e: lam_d[e]):
            s.append(f"\\draw[{loss_style(length(P, e) / sc)}] {pt(P, e[0], ox, oy)} -- {pt(P, e[1], ox, oy)};%")
        s += draw_vertices(P, F, (ox, oy))
    s.append(f"\\node[em label,fill=opNeutral,anchor=south] at ({bx:.4f},{by_top + 0.04:.4f}) {{$\\lambda = 4$}};%")
    for xh in (-0.45, 0.45):
        s.append(f"\\node[em label,fill=opNeutral,anchor=north] at ({bx + xh:.4f},{by_bot - 0.04:.4f}) {{$1$}};%")
    for yh in (0.34, -0.34):
        s.append(f"\\node[em label,fill=opNeutral,anchor=west] at ({bx + 0.03:.4f},{by_bot + yh:.4f}) {{$0$}};%")
    s.append(f"\\draw[-latex,opInk,line width=.4pt] ({bx:.4f},{by_top - sc - 0.06:.4f}) -- "
             f"node[em label,anchor=west,xshift=1pt] {{split, $g(s)={eb - ea:.0f}$}} "
             f"({bx:.4f},{by_bot + sc + 0.06:.4f});%")
    rx = bx + 2 * sc + 0.2
    s.append(f"\\node[em label,anchor=west,align=left] at ({rx:.4f},{by_top:.4f}) "
             f"{{$\\mathcal{{E}}={eb:.2f}$\\\\$|E|=5$\\\\$\\bar\\lambda={eb / 5:.2f}$}};%")
    s.append(f"\\node[em label,anchor=west,align=left] at ({rx:.4f},{by_bot:.4f}) "
             f"{{$\\mathcal{{E}}={ea:.2f}$\\\\$|E|=8$\\\\$\\bar\\lambda={ea / 8:.2f}$}};%")

    # Shared colour key, centred below both panels.
    ky = min(bottom, by_bot - sc) - 0.62
    color_key(s, 5.55, ky)
    s += FOOTER
    (out / "edge-loss-mesh.tikz").write_text("\n".join(s) + "\n")


