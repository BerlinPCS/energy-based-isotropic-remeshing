"""Generate halfedge.tikz (Figure fig:halfedge-data-structure, Chapter 2).

Left: the records of the halfedge data structure (fields as in PMP Section 2.3), each field with its type in
gray; an arrow marks a reference to another element. Right: two triangles f = (a, b, l) and g = (b, a, r), both
counter-clockwise, sharing the edge {a, b}. The halfedge h runs from a to b inside f, so vertex(h) = b,
face(h) = f, next(h) = b->l, prev(h) = l->a and opposite(h) = b->a inside g. Halfedges are drawn shortened and
moved towards the centroid of their face; the four boundary halfedges a->l->b->r->a (no face) are moved outwards
and dashed.
"""

from math import atan2, degrees, hypot

from common.style import define_color

P = {"a": (0.0, 0.0), "b": (0.0, 3.0), "l": (-2.75, 1.5), "r": (2.75, 1.5)}
FACES = {"f": ("a", "b", "l"), "g": ("b", "a", "r")}
SHORTEN = 0.14  # fraction cut from both ends
INSET = 0.15  # cm towards the face centroid
RECORDS = (-3.05, 2.75)  # north-east corner of the halfedge record, left of the triangles


def centroid(face):
    return tuple(sum(P[v][i] for v in face) / 3 for i in range(2))


def halfedge(p, q, face, side=1):
    """Shortened halfedge p->q, moved towards the centroid of face (side=1) or away from it (side=-1)."""
    (px, py), (qx, qy), (cx, cy) = P[p], P[q], centroid(FACES[face])
    dx, dy = qx - px, qy - py
    length = hypot(dx, dy)
    nx, ny = -dy / length, dx / length  # left normal; faces are counter-clockwise, so it points inwards
    if side * ((cx - px) * nx + (cy - py) * ny) < 0:
        nx, ny = -nx, -ny
    s = (px + SHORTEN * dx + INSET * nx, py + SHORTEN * dy + INSET * ny)
    t = (qx - SHORTEN * dx + INSET * nx, qy - SHORTEN * dy + INSET * ny)
    return s, t, (nx, ny)


def c(p):
    return f"({p[0]:.3f},{p[1]:.3f})"


def generate(out):
    lines = [
        "% Generated by scripts/figures/halfedge.py; edit the generator, not this file.",
        r"\begingroup",
        define_color("opInk"),
        define_color("opNeutral"),
        define_color("opBefore"),
        define_color("opAfter"),
        define_color("opAfterFill"),
        r"\begin{tikzpicture}[",
        r"  he edge/.style={draw=opInk,line width=.5pt,line join=round},",
        r"  he arrow/.style={->,>=stealth,line width=.8pt,line cap=round},",
        r"  he boundary/.style={draw=opInk!45,dash pattern=on 2.4pt off 1.6pt},",
        r"  he label/.style={font=\footnotesize,inner sep=1pt},",
        r"  he record/.style={draw=opInk,line width=.5pt,rounded corners=1pt,font=\footnotesize,inner sep=2pt,",
        r"    anchor=north west}]",
    ]
    # Records: type (gray, an arrow marks a reference) and name (teal if the diagram shows it for h).
    def field(kind, name, ref=False):
        kind = rf"$\rightarrow$\,{kind}" if kind != "Point" else kind
        name = rf"\textcolor{{opAfter}}{{\texttt{{{name}}}}}" if ref else rf"\texttt{{{name}}}"
        return rf"\textcolor{{opInk!55}}{{{kind}}} & {name}"

    def record(title, fields):
        rows = r"\\".join(fields)
        return (rf"\begin{{tabular}}{{@{{}}l@{{\hspace{{.5em}}}}l@{{}}}}\multicolumn{{2}}{{@{{}}l@{{}}}}{{\textbf{{{title}}}}}"
                rf"\\\hline {rows}\end{{tabular}}")

    vertex = record("Vertex", [field("Point", "position"), field("Halfedge", "halfedge")])
    face = record("Face", [field("Halfedge", "halfedge")])
    half = record("Halfedge", [field("Vertex", "vertex", True), field("Face", "face", True),
                               field("Halfedge", "next", True), field("Halfedge", "prev", True),
                               field("Halfedge", "opposite", True)])
    lines.append(rf"\node[he record,anchor=north east] (rech) at ({RECORDS[0]:.2f},{RECORDS[1]:.2f}) {{{half}}};")
    lines.append(rf"\node[he record,anchor=north east,xshift=-6pt] (recv) at (rech.north west) {{{vertex}}};")
    lines.append(rf"\node[he record,yshift=-6pt] (recf) at (recv.south west) {{{face}}};")
    # Faces and edges.
    lines.append(rf"\fill[opAfter!30] {c(P['a'])} -- {c(P['b'])} -- {c(P['l'])} -- cycle;")
    lines.append(rf"\fill[opNeutral] {c(P['b'])} -- {c(P['a'])} -- {c(P['r'])} -- cycle;")
    for p, q in (("a", "b"), ("b", "l"), ("l", "a"), ("a", "r"), ("r", "b")):
        lines.append(rf"\draw[he edge] {c(P[p])} -- {c(P[q])};")
    # Halfedges: h, its references, and the remaining two of g for context.
    arrows = {
        "h": ("a", "b", "f", "opBefore"),
        "next": ("b", "l", "f", "opAfter"),
        "prev": ("l", "a", "f", "opAfter"),
        "opposite": ("b", "a", "g", "opAfter"),
        "g1": ("a", "r", "g", "opInk!45"),
        "g2": ("r", "b", "g", "opInk!45"),
    }
    geo = {}
    for name, (p, q, face, colour) in arrows.items():
        s, t, n = halfedge(p, q, face)
        geo[name] = (s, t, n)
        width = ",line width=1.1pt" if name == "h" else ""
        lines.append(rf"\draw[he arrow,draw={colour}{width}] {c(s)} -- {c(t)};")
    for p, q, face in (("a", "l", "f"), ("l", "b", "f"), ("b", "r", "g"), ("r", "a", "g")):  # boundary loop
        s, t, _ = halfedge(p, q, face, side=-1)
        lines.append(rf"\draw[he arrow,he boundary] {c(s)} -- {c(t)};")

    def mid(name, extra):
        s, t, n = geo[name]
        return ((s[0] + t[0]) / 2 + extra * n[0], (s[1] + t[1]) / 2 + extra * n[1])

    def angle(name):
        s, t, _ = geo[name]
        a = degrees(atan2(t[1] - s[1], t[0] - s[0]))
        return a - 180 if a > 90 else a + 180 if a < -90 else a

    hs, ht, hn = geo["h"]
    lines.append(rf"\node[he label,text=opBefore,anchor=east] at ({hs[0] + 0.3 * (ht[0] - hs[0]) + 0.06 * hn[0]:.3f},{hs[1] + 0.3 * (ht[1] - hs[1]):.3f}) {{$h$}};")
    lines.append(rf"\node[he label,text=opAfter,anchor=west] at {c(mid('opposite', 0.06))} {{$\operatorname{{opposite}}(h)$}};")
    lines.append(rf"\node[he label,text=opAfter,rotate={angle('next'):.1f},anchor=south] at {c(mid('next', -0.42))} {{$\operatorname{{next}}(h)$}};")
    lines.append(rf"\node[he label,text=opAfter,rotate={angle('prev'):.1f},anchor=north] at {c(mid('prev', -0.42))} {{$\operatorname{{prev}}(h)$}};")
    cf = centroid(FACES["f"])
    lines.append(rf"\node[he label,text=opAfter] at ({cf[0] - 0.3:.3f},{cf[1] + 0.1:.3f}) {{$f=\operatorname{{face}}(h)$}};")
    # Vertices.
    for v in ("a", "l", "r"):
        lines.append(rf"\draw[draw=opInk,fill=white,line width=.5pt] {c(P[v])} circle[radius=1.8pt];")
    lines.append(rf"\draw[draw=black,fill=opAfter,line width=.5pt] {c(P['b'])} circle[radius=2.1pt];")
    lines.append(rf"\node[he label,text=opAfter,anchor=south] at ({P['b'][0]:.3f},{P['b'][1] + 0.14:.3f}) {{$\operatorname{{vertex}}(h)$}};")
    lines += [r"\end{tikzpicture}", r"\endgroup"]
    (out / "halfedge.tikz").write_text("\n".join(line + "%" for line in lines) + "\n")
