"""Table eval-comparison (Ch. 4, Discussion): ten cycles and the best approaches relative to five baseline cycles, as
the median over all 30 cases.

Writes comparison-table.tex.
"""
from shared.dataset import ANGLE_TAIL, DEVIATION, LOSS, OBJECTIVES, TIME, VALENCE
from shared.style import ANGLE_TAIL_SYMBOL, DEVIATION_SYMBOL, LOSS_SYMBOL, TIME_SYMBOL, VALENCE_SYMBOL, decimal_column

ROWS = [(LOSS_SYMBOL, LOSS, 3), (ANGLE_TAIL_SYMBOL, ANGLE_TAIL, 3), (VALENCE_SYMBOL, VALENCE, 3),
        (DEVIATION_SYMBOL, DEVIATION, 3), (TIME_SYMBOL, TIME, 2)]


def generate(data, out):
    columns = [data.fixed(10), data.runs('repeated'), data.runs('ordered'),
               *(data.runs('alternating', objective) for objective in OBJECTIVES)]
    rows = [[name, *(f'{data.median_ratio(runs, metric):.{digits}f}' for runs in columns)]
            for name, metric, digits in ROWS]
    spec = ''.join(decimal_column([row[index] for row in rows]) for index in range(1, len(rows[0])))
    lines = ['% Generated by scripts/figures/comparison_table.py.', rf'\begin{{tabular}}{{@{{}}l{spec}@{{}}}}',
             r'\toprule', r'& & & & \multicolumn{4}{c}{Alternating} \\', r'\cmidrule(l){5-8}',
             r'& {10 cycles} & {Repeated} & {Ordered} & {Sum} & {Max.} & {Local\ avg.} & {Global\ avg.} \\',
             r'\midrule', *(' & '.join(row) + r' \\' for row in rows), r'\bottomrule', r'\end{tabular}']
    (out / 'comparison-table.tex').write_text('\n'.join(lines) + '\n')
