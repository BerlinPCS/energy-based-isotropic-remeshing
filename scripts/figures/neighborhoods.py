"""Generate neighborhoods.tikz (Figure fig:vertex-neighborhoods, Chapter 2).

A flat three-ring patch of a regular triangulation in which one edge next to the centre vertex v is flipped, so
that v has valence 7. The interior vertices other than v are then relaxed by a few uniform Laplacian steps and
jittered slightly, so the patch does not look like a lattice. The one-ring N1(v) and two-ring N2(v) are computed
from the connectivity (breadth-first search), not set by hand, and the script asserts val(v) = 7 and that no
triangle is flipped.
"""

from math import atan2, cos, degrees, pi, sin, sqrt

from common.style import define_color

RINGS = 3
SCALE = (0.94, 0.56)  # cm per lattice unit in x and y; wider than tall to save vertical space


def lattice():
    coords = {}
    for i in range(-RINGS, RINGS + 1):
        for j in range(-RINGS, RINGS + 1):
            if max(abs(i), abs(j), abs(i + j)) <= RINGS:
                coords[(i, j)] = (i + 0.5 * j, j * sqrt(3) / 2)
    faces = []
    for (i, j) in coords:
        for tri in (((i, j), (i + 1, j), (i, j + 1)), ((i + 1, j), (i + 1, j + 1), (i, j + 1))):
            if all(t in coords for t in tri):
                faces.append(tri)
    return coords, faces


def flip(faces, a, b):
    """Replace the edge {a, b} by the other diagonal of its two triangles (orientation preserved)."""
    pair = [f for f in faces if a in f and b in f]
    assert len(pair) == 2
    (f1, f2) = pair
    w = next(x for x in f1 if x not in (a, b))
    x = next(y for y in f2 if y not in (a, b))
    # Orient f1 as (a, b, w); then the flipped triangles are (w, x, b)... keep counter-clockwise order below.
    rest = [f for f in faces if f not in pair]
    return rest + [(a, x, w), (b, w, x)]


def area2(p, q, r):
    return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])


def generate(out):
    coords, faces = lattice()
    centre = (0, 0)
    faces = flip(faces, (1, 0), (0, 1))
    pos = dict(coords)
    for f in faces:  # make every face counter-clockwise
        assert abs(area2(*(pos[x] for x in f))) > 1e-9
    faces = [f if area2(*(pos[x] for x in f)) > 0 else (f[0], f[2], f[1]) for f in faces]

    nbrs = {k: set() for k in coords}
    for f in faces:
        for i in range(3):
            nbrs[f[i]].add(f[(i + 1) % 3])
            nbrs[f[(i + 1) % 3]].add(f[i])
    boundary = {k for k in coords if max(abs(k[0]), abs(k[1]), abs(k[0] + k[1])) == RINGS}
    for _ in range(4):
        new = dict(pos)
        for k in coords:
            if k == centre or k in boundary:
                continue
            new[k] = (sum(pos[n][0] for n in nbrs[k]) / len(nbrs[k]), sum(pos[n][1] for n in nbrs[k]) / len(nbrs[k]))
        pos = new
    for (i, j) in coords:
        if (i, j) != centre:
            amp = 0.05 if (i, j) in boundary else 0.08
            angle = 2.1 * i + 1.3 * j + 0.7 * i * j
            pos[(i, j)] = (pos[(i, j)][0] + amp * cos(angle), pos[(i, j)][1] + amp * sin(angle))
    assert all(area2(*(pos[x] for x in f)) > 0.05 for f in faces), "flipped or thin triangle"

    ring1 = nbrs[centre]
    ring2 = set().union(*(nbrs[n] for n in ring1)) - ring1 - {centre}
    assert len(ring1) == 7, len(ring1)

    def pt(k):
        return f"({pos[k][0] * SCALE[0]:.4f},{pos[k][1] * SCALE[1]:.4f})"

    lines = [
        "% Generated by scripts/figures/neighborhoods.py; edit the generator, not this file.",
        r"\begingroup",
        define_color("opInk"),
        define_color("opNeutral"),
        define_color("opBefore"),
        define_color("opBeforeFill"),
        define_color("opAfter"),
        define_color("opAfterFill"),
        r"\begin{tikzpicture}[nb edge/.style={draw=opInk,line width=.45pt,line join=round}]",
    ]
    for f in faces:
        if centre in f:
            fill = "opBeforeFill"
        elif all(x in ring1 or x in ring2 for x in f):
            fill = "opAfterFill"
        else:
            fill = "opNeutral"
        lines.append(rf"\filldraw[nb edge,fill={fill}] {pt(f[0])} -- {pt(f[1])} -- {pt(f[2])} -- cycle;")
    for k in sorted(coords):
        if k == centre:
            style, radius = "draw=black,fill=black", 2.3
        elif k in ring1:
            style, radius = "draw=black,fill=opBefore", 2.0
        elif k in ring2:
            style, radius = "draw=black,fill=opAfter", 2.0
        else:
            style, radius = "draw=opInk,fill=white", 1.5
        lines.append(rf"\draw[{style},line width=.45pt] {pt(k)} circle[radius={radius}pt];")
    # Label v in the widest angular gap between its edges (in drawing coordinates).
    angles = sorted(atan2((pos[n][1] - pos[centre][1]) * SCALE[1], (pos[n][0] - pos[centre][0]) * SCALE[0]) for n in ring1)
    gaps = [((angles[(k + 1) % len(angles)] - a) % (2 * pi), a) for k, a in enumerate(angles)]
    width, start = max(gaps)
    mid = start + width / 2
    x, y = pos[centre][0] * SCALE[0] + 0.2 * cos(mid), pos[centre][1] * SCALE[1] + 0.2 * sin(mid)
    lines.append(rf"\node[font=\small,text=black,inner sep=0pt] at ({x:.4f},{y:.4f}) {{$v$}};")
    lines += [r"\end{tikzpicture}", r"\endgroup"]
    (out / "neighborhoods.tikz").write_text("\n".join(line + "%" for line in lines) + "\n")
