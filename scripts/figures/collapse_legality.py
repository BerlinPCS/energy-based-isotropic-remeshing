"""Generate collapse-legality.tikz: a collapse that breaks the first legality rule of Hoppe et al. (1993, sec. 4.2).

A flat patch in which the edge {u, v} and the vertex w span three edges without a face (an empty triangle): a vertex x
inside the cycle u, v, w is connected to all three. w is adjacent to both u and v, but {u, v, w} is not a face, so the
collapse of {u, v} is illegal. The right panel shows its result: u and v merge into m, the edges {u, w} and {v, w} both
become {m, w} (a double edge), and the faces {u, x, w} and {v, x, w} become the same face {m, x, w}. The double edge is
drawn as two arcs. The script checks the configuration before writing.
"""

from common.style import define_color

# Left panel: vertex positions in cm.
BEFORE = {'u': (-0.9, 0.0), 'v': (0.9, 0.0), 'w': (0.0, 1.55), 'x': (0.0, 0.55), 'y': (0.0, -0.95),
          'a': (-1.75, 0.35), 'b': (1.75, 0.35)}
FACES = [('u', 'v', 'x'), ('v', 'w', 'x'), ('w', 'u', 'x'), ('u', 'y', 'v'), ('u', 'w', 'a'), ('v', 'b', 'w'), ('a', 'y', 'u'), ('v', 'y', 'b')]
EDGE = ('u', 'v')
SHIFT = 4.9  # cm between the panels


def edges(faces):
    return {frozenset(p) for f in faces for p in ((f[0], f[1]), (f[1], f[2]), (f[2], f[0]))}


def check():
    u, v = EDGE
    es = edges(FACES)
    common = {k for k in BEFORE if frozenset((u, k)) in es and frozenset((v, k)) in es}
    faced = {k for f in FACES if u in f and v in f for k in f if k not in EDGE}
    assert common - faced == {'w'}, (common, faced)
    after = [tuple('m' if k in EDGE else k for k in f) for f in FACES if not (u in f and v in f)]
    keys = [frozenset(f) for f in after]
    assert len(keys) - len(set(keys)) == 1  # {m, x, w} twice
    return after


def generate(out):
    check()
    p = BEFORE
    lines = [r'% Generated by scripts/figures/collapse_legality.py; do not edit.', '{%']
    lines += [define_color(c) + '%' for c in ('opInk', 'opNeutral', 'opBefore', 'opOperand', 'opBeforeFill', 'opAfter',
                                              'opAfterFill')]
    lines += [r'\begin{tikzpicture}[line join=round, font=\footnotesize,',
              r'  vtx/.style={circle, fill=opInk, inner sep=0pt, minimum size=3.2pt},',
              r'  lab/.style={text=opInk, inner sep=1.5pt}]']
    c = lambda k, dx=0.0: f'({p[k][0] + dx:.3f},{p[k][1]:.3f})'
    # Before.
    for f in FACES:
        fill = 'opBeforeFill' if 'x' in f else 'opNeutral'
        lines.append(rf'\filldraw[fill={fill}, draw=opInk, line width=0.5pt] ' + ' -- '.join(c(k) for k in f) + ' -- cycle;')
    lines.append(rf'\draw[opBefore, line width=1.4pt] {c("v")} -- {c("w")} -- {c("u")};')
    lines.append(rf'\draw[opOperand, line width=1.6pt] {c("u")} -- {c("v")};')
    for k, anchor in (('u', 'south west'), ('v', 'south east'), ('w', 'north'), ('x', 'south'), ('y', 'north'),
                      ('a', 'west'), ('b', 'east')):
        lines.append(rf'\node[vtx] at {c(k)} {{}};')
    for k, anchor in (('u', 'north east'), ('v', 'north west'), ('w', 'south'), ('x', 'north')):
        lines.append(rf'\node[lab, anchor={anchor}] at {c(k)} {{${k}$}};')
    lines.append(rf'\node[lab] at (0,-1.35) {{before}};')
    # Arrow.
    lines.append(rf'\draw[-latex, opInk, line width=0.6pt] (2.05,0.4) -- ({SHIFT - 2.05:.2f},0.4);')
    # After: u and v at their midpoint m; the two copies of {m, x, w} share the double edge {m, w}.
    m = (SHIFT, 0.0)
    q = {k: (xy[0] + SHIFT, xy[1]) for k, xy in p.items()}
    q['m'] = m
    d = lambda k: f'({q[k][0]:.3f},{q[k][1]:.3f})'
    q['x'] = (SHIFT + 0.32, 0.7)  # moved off the line m-w so that the face {m, x, w} stays visible
    for f in (('m', 'w', 'a'), ('m', 'b', 'w'), ('a', 'y', 'm'), ('m', 'y', 'b')):
        lines.append(rf'\filldraw[fill=opNeutral, draw=opInk, line width=0.5pt] ' + ' -- '.join(d(k) for k in f) + ' -- cycle;')
    lines.append(rf'\filldraw[fill=opAfterFill, draw=opInk, line width=0.5pt] {d("m")} -- {d("x")} -- {d("w")} -- cycle;')
    lines.append(rf'\draw[opBefore, line width=1.4pt] {d("m")} to[bend left=22] {d("w")};')
    lines.append(rf'\draw[opBefore, line width=1.4pt] {d("m")} to[bend right=22] {d("w")};')
    for k in ('m', 'w', 'x', 'y', 'a', 'b'):
        lines.append(rf'\node[vtx] at {d(k)} {{}};')
    for k, anchor in (('m', 'north east'), ('w', 'south'), ('x', 'west')):
        lines.append(rf'\node[lab, anchor={anchor}] at {d(k)} {{${k}$}};')
    lines.append(rf'\node[lab] at ({SHIFT},-1.35) {{after}};')
    lines += [r'\end{tikzpicture}%', '}%']
    (out / 'collapse-legality.tikz').write_text('\n'.join(lines) + '\n')
