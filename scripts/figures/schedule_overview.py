"""Generate the schematic schedule overview of Chapter 3 (Section sec:approaches).

Writes schedule-overview.tikz: one row per approach, time running to the right (not to scale). Phase
cycles are drawn as four cells (split, collapse, flip, relocation). Queue and batch stages are drawn as bars of
thin ticks whose colours stand for the operation type of each applied edit; the colours are drawn uniformly at
random (fixed seed) and do not show measured operation mixes. The end of each row names its stopping rule.
"""

import random

from shared.style import define_color

COLORS = {"split": "D77D43", "collapse": "35A39E", "flip": "6B7FD7", "relocation": "9AA3AB"}
CELL = 0.17  # width of one phase cell, cm
ROW = 0.62  # row distance, cm
X0 = 3.05  # start of the time axis, cm
TICK = 0.045  # spacing of queue ticks, cm


class Row:
    def __init__(self, label, stop):
        self.label, self.stop, self.items = label, stop, []

    def cycles(self, count, sorted_phases=False):
        self.items += [("cycle", sorted_phases)] * count
        return self

    def queue(self, length, knee=False):
        self.items.append(("queue", length, knee))
        return self

    def batch(self, rounds, length):
        self.items += [("batch", length)] * rounds
        return self


ROWS = [
    Row("Baseline", r"$k$ cycles").cycles(5),
    Row("Repeated cycles", "stagnation").cycles(8),
    Row("Repeated ordered cycles", "stagnation").cycles(8, sorted_phases=True),
    Row("Dynamic queue", "no improving candidate").queue(6.2),
    Row("Batched processing", "no improving candidate").batch(4, 1.35),
    Row("Hybrid", "no improving candidate").cycles(2).queue(4.6),
    Row("Alternating", "no improving candidate").cycles(1).queue(0.9, knee=True).cycles(1).queue(0.75, knee=True)
    .cycles(1).queue(0.6, knee=True).queue(1.4),
]


def generate(out):
    rng = random.Random(20261019)
    lines = [
        "% Generated by scripts/figures/schedule_overview.py; edit the generator for changes.",
        r"\begingroup",
        *(rf"\definecolor{{sched{name}}}{{HTML}}{{{value}}}" for name, value in COLORS.items()),
        define_color("schedInk"),
        define_color("schedQueue"),
        r"\begin{tikzpicture}[",
        r"  sched label/.style={font=\footnotesize,text=schedInk,anchor=east},",
        r"  sched stop/.style={font=\scriptsize,text=schedInk,anchor=west},",
        r"  sched frame/.style={draw=schedInk,line width=.35pt}]",
    ]
    height = 0.34
    for r, row in enumerate(ROWS):
        y = -r * ROW
        lines.append(rf"\node[sched label] at ({X0 - 0.12:.3f},{y:.3f}) {{{row.label}}};")
        x = X0
        for item in row.items:
            if item[0] == "cycle":
                for phase in ("split", "collapse", "flip", "relocation"):
                    x1 = x + CELL
                    lines.append(rf"\fill[sched{phase}] ({x:.3f},{y - height / 2:.3f}) rectangle "
                                 rf"({x1:.3f},{y + height / 2:.3f});")
                    if item[1] and phase in ("split", "collapse"):
                        # A descending ramp marks a phase whose candidates are ordered by length.
                        lines.append(rf"\fill[white,opacity=.55] ({x:.3f},{y + height / 2:.3f}) -- "
                                     rf"({x1:.3f},{y + height / 2:.3f}) -- ({x1:.3f},{y - height / 2:.3f}) -- cycle;")
                    x = x1
                lines.append(rf"\draw[sched frame] ({x - 4 * CELL:.3f},{y - height / 2:.3f}) rectangle "
                             rf"({x:.3f},{y + height / 2:.3f});")
                x += 0.05
            elif item[0] in ("queue", "batch"):
                length = item[1]
                start = x
                if item[0] == "batch":
                    # Collect and sort all accepted candidates, then walk the sorted list.
                    lines.append(rf"\fill[schedInk] ({x:.3f},{y - height / 2:.3f}) rectangle "
                                 rf"({x + 0.07:.3f},{y + height / 2:.3f});")
                    x += 0.07
                lines.append(rf"\fill[schedQueue] ({x:.3f},{y - height / 2:.3f}) rectangle "
                             rf"({start + length:.3f},{y + height / 2:.3f});")
                t = x + TICK / 2
                while t < start + length - TICK / 4:
                    phase = rng.choice(list(COLORS))
                    lines.append(rf"\draw[sched{phase},line width=.55pt] ({t:.3f},{y - height / 2 + 0.03:.3f}) -- "
                                 rf"({t:.3f},{y + height / 2 - 0.03:.3f});")
                    t += TICK
                lines.append(rf"\draw[sched frame] ({start:.3f},{y - height / 2:.3f}) rectangle "
                             rf"({start + length:.3f},{y + height / 2:.3f});")
                x = start + length
                if item[0] == "queue" and item[2]:
                    lines.append(rf"\node[font=\tiny\bfseries,text=schedInk,anchor=south] at "
                                 rf"({x:.3f},{y + height / 2 - 0.04:.3f}) {{K}};")
                x += 0.05
        lines.append(rf"\draw[schedInk,line width=.9pt] ({x + 0.02:.3f},{y - height / 2 - 0.05:.3f}) -- "
                     rf"({x + 0.02:.3f},{y + height / 2 + 0.05:.3f});")
        lines.append(rf"\node[sched stop] at ({x + 0.08:.3f},{y:.3f}) {{{row.stop}}};")

    # Legend.
    y = -len(ROWS) * ROW + 0.05
    x = X0 - 2.9
    entries = [(f"sched{name}", name) for name in COLORS]
    for color, name in entries:
        lines.append(rf"\fill[{color}] ({x:.3f},{y - 0.09:.3f}) rectangle ({x + 0.18:.3f},{y + 0.09:.3f});")
        lines.append(rf"\node[sched stop] at ({x + 0.2:.3f},{y:.3f}) {{{name}}};")
        x += 0.42 + 0.155 * len(name)
    lines.append(rf"\fill[schedsplit] ({x:.3f},{y - 0.09:.3f}) rectangle ({x + 0.18:.3f},{y + 0.09:.3f});")
    lines.append(rf"\fill[white,opacity=.55] ({x:.3f},{y + 0.09:.3f}) -- ({x + 0.18:.3f},{y + 0.09:.3f}) -- "
                 rf"({x + 0.18:.3f},{y - 0.09:.3f}) -- cycle;")
    lines.append(rf"\node[sched stop] at ({x + 0.2:.3f},{y:.3f}) {{sorted phase}};")
    x += 2.15
    lines.append(rf"\fill[schedInk] ({x:.3f},{y - 0.09:.3f}) rectangle ({x + 0.07:.3f},{y + 0.09:.3f});")
    lines.append(rf"\node[sched stop] at ({x + 0.1:.3f},{y:.3f}) {{collect and sort}};")
    x += 2.45
    lines.append(rf"\node[font=\tiny\bfseries,text=schedInk] at ({x + 0.05:.3f},{y:.3f}) {{K}};")
    lines.append(rf"\node[sched stop] at ({x + 0.15:.3f},{y:.3f}) {{knee}};")
    lines += [r"\end{tikzpicture}", r"\endgroup"]
    (out / "schedule-overview.tikz").write_text("\n".join(line + "%" for line in lines) + "\n")
