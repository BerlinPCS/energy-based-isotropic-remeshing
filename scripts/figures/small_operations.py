"""Generate small-operations.tikz, the operation diagram, from the author's Blender/PMP OBJ pairs.

The full 3D coordinates determine face lighting; an overhead orthographic camera preserves the XY layout. All panels
share a single translation, scale, camera and light.
"""

from math import sqrt
from pathlib import Path

from shared.edit_pairs import EditPair, edges, read_obj
from shared.style import define_color

MESHES = Path(__file__).resolve().parent / "small_operations_meshes"
OPERATIONS = (
    ("split", "Edge split"),
    ("collapse", "Edge collapse"),
    ("flip", "Edge flip"),
    ("smooth", "Tangential smoothing"),
)
# Direction towards the light: upper left, above the surface. Fixed across panels.
LIGHT = (-0.55, 0.65, 0.52)
AMBIENT = 0.64  # 0.48 before 2026-10-19; higher means flatter shading


def read_mesh(path):
    vertices, faces = read_obj(path)
    # The overhead view must not silently introduce a folded projection.
    for face in faces:
        a, b, c = (vertices[i] for i in face)
        area2 = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
        if area2 <= 1e-10:
            raise ValueError(f"Degenerate/reversed XY projection: {path}")
    return vertices, faces


def face_brightness(vertices, face):
    """Lambertian flat shading from the actual 3D triangle, plus ambient light."""
    a, b, c = (vertices[i] for i in face)
    u = tuple(b[i] - a[i] for i in range(3))
    v = tuple(c[i] - a[i] for i in range(3))
    normal = (u[1] * v[2] - u[2] * v[1],
              u[2] * v[0] - u[0] * v[2],
              u[0] * v[1] - u[1] * v[0])
    normal_length = sqrt(sum(x * x for x in normal))
    light_length = sqrt(sum(x * x for x in LIGHT))
    cosine = sum(n * l for n, l in zip(normal, LIGHT)) / (normal_length * light_length)
    return 100 * (AMBIENT + (1 - AMBIENT) * max(0, min(1, cosine)))


def read_pairs():
    return [(title, EditPair(name, read_mesh(MESHES / f"small_{name}.obj"), read_mesh(MESHES / f"small_{name}_result.obj")))
            for name, title in OPERATIONS]


def generate(out):
    pairs = read_pairs()
    all_vertices = [v for _, pair in pairs for mesh in (pair.before, pair.after) for v in mesh[0]]
    xmin, xmax = min(v[0] for v in all_vertices), max(v[0] for v in all_vertices)
    ymin, ymax = min(v[1] for v in all_vertices), max(v[1] for v in all_vertices)
    cx, cy = (xmin + xmax) / 2, (ymin + ymax) / 2
    scale = 2.43 / (xmax - xmin)

    lines = [
        "% Generated by scripts/figures/small_operations.py; edit the generator for geometry changes.",
        "% Full 3D OBJ vertices; overhead orthographic camera, light from upper left.",
        r"\begingroup",
        define_color("opInk"),
        define_color("opNeutral"),
        define_color("opBefore"),
        define_color("opOperand"),
        define_color("opBeforeFill"),
        define_color("opAfter"),
        define_color("opAfterFill"),
        r"\begin{tikzpicture}[x={(1cm,0cm)},y={(0cm,1cm)},z={(0cm,0cm)},",
        r"  op edge/.style={draw=opInk,line width=.55pt,line cap=round,line join=round},",
        r"  op boundary/.style={op edge,line width=.8pt},",
        r"  op vertex/.style={draw=opInk,fill=white,line width=.55pt},",
        r"  op label/.style={font=\small,text=opInk},",
        r"  op arrow/.style={->,>=stealth,draw=opInk,line width=.8pt}]",
        r"\path[use as bounding box] (-1.40,-4.95) rectangle (10.55,1.62);",
    ]

    def point(v):
        return f"({(v[0] - cx) * scale:.6f},{(v[1] - cy) * scale:.6f},{v[2] * scale:.6f})"

    for col, (title, pair) in enumerate(pairs):
        x = 3.05 * col
        name, before, after = pair.operation, pair.before, pair.after

        lines += [f"% {name}", rf"\node[op label,font=\footnotesize\bfseries] at ({x:.2f},1.43) {{{chr(97 + col)}) {title}}};"]
        for row, (mesh, labels, accent, y) in enumerate(((before, pair.labels_before, "opBefore", 0), (after, pair.labels_after, "opAfter", -3.12))):
            vertices, faces = mesh
            prefix = f"p{col}r{row}v"
            lines.append(rf"\begin{{scope}}[shift={{({x:.2f},{y:.2f})}}]")
            for i, v in enumerate(vertices):
                lines.append(rf"\coordinate ({prefix}{i}) at {point(v)};")
            for face in faces:
                changed = tuple(sorted(labels[i] for i in face)) not in pair.common_faces
                fill = accent + "Fill" if changed else "opNeutral"
                brightness = face_brightness(vertices, face)
                path = " -- ".join(f"({prefix}{i})" for i in face)
                lines.append(rf"\fill[{fill}!{brightness:.2f}!black] {path} -- cycle;")
            for edge, count in sorted(edges(faces).items()):
                signature = tuple(sorted(labels[i] for i in edge))
                changed = signature not in pair.common_edges
                style = "op boundary" if count == 1 else "op edge"
                if row == 0 and signature in pair.operand_edges:
                    style += ",draw=opOperand,line width=1.35pt"
                elif changed:
                    style += f",draw={accent},line width=.95pt"
                lines.append(rf"\draw[{style}] ({prefix}{edge[0]}) -- ({prefix}{edge[1]});")
            changed_vertices = pair.removed_vertices if row == 0 else pair.added_vertices
            for i in range(len(vertices)):
                changed = labels[i] in changed_vertices
                style = "op vertex,draw=black,line width=.55pt" if changed else "op vertex"
                if changed:
                    style += ",fill=opOperand" if row == 0 and labels[i] in pair.removed_vertices else f",fill={accent}"
                lines.append(rf"\draw[{style}] ({prefix}{i}) circle[radius=1.8pt];")
            lines.append(r"\end{scope}")
        lines.append(rf"\draw[op arrow] ({x:.2f},-1.33) -- ({x:.2f},-1.78);")

    lines += [
        r"\draw[draw=opBefore,line width=.95pt] (.25,-4.61) -- (.58,-4.61);",
        r"\draw[draw=black,fill=opBefore,line width=.55pt] (.415,-4.61) circle[radius=1.8pt];",
        r"\node[op label,anchor=west,font=\footnotesize] at (.70,-4.61) {affected elements before operation};",
        r"\draw[draw=opAfter,line width=.95pt] (5.15,-4.61) -- (5.48,-4.61);",
        r"\draw[draw=black,fill=opAfter,line width=.55pt] (5.315,-4.61) circle[radius=1.8pt];",
        r"\node[op label,anchor=west,font=\footnotesize] at (5.60,-4.61) {affected elements after operation};",
        r"\end{tikzpicture}",
        r"\endgroup",
    ]
    # Suppress inter-line TeX spaces so the include's width is the picture's width.
    (out / "small-operations.tikz").write_text("\n".join(line + "%" for line in lines) + "\n")

